CREATE TABLE [dbo].[PM_PROJECT_FILES] (
    [ID]       INT              IDENTITY (1, 1) NOT NULL,
    [GID]      UNIQUEIDENTIFIER NOT NULL,
    [S_CR]     INT              NOT NULL,
    [S_CDT]    DATETIME         NOT NULL,
    [S_MR]     INT              NULL,
    [S_MDT]    DATETIME         NULL,
    [ARC]      INT              NULL,
    [VNESHID]  INT              NOT NULL,
    [FILENAME] NVARCHAR (255)   NOT NULL,
    [FILESIZE] INT              NOT NULL,
    [FILEDESC] NTEXT            NULL,
    [FILEDATE] DATETIME         NOT NULL,
    [FILEBLOB] IMAGE            NULL,
    PRIMARY KEY CLUSTERED ([ID] ASC),
    CONSTRAINT [FK_PM_PROJECT_FILES_VNESHID] FOREIGN KEY ([VNESHID]) REFERENCES [dbo].[PM_PROJECT] ([ID]) ON DELETE CASCADE
);


GO
CREATE NONCLUSTERED INDEX [IX_PM_PROJECT_FILES]
    ON [dbo].[PM_PROJECT_FILES]([VNESHID] ASC);

