CREATE TABLE [dbo].[PR_REV_PARAMS] (
    [ID]          INT              IDENTITY (1, 1) NOT NULL,
    [GID]         UNIQUEIDENTIFIER NULL,
    [S_CR]        INT              NULL,
    [S_CDT]       DATETIME         NULL,
    [S_MR]        INT              NULL,
    [S_MDT]       DATETIME         NULL,
    [REVISIONID]  INT              NOT NULL,
    [PARAMID]     INT              NOT NULL,
