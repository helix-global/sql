    [ONLYOPTION]  INT              NULL,
    [ARC]         INT              NULL,
    [ONLYOPTION2] INT              NULL,
    [ONLYOPTION3] INT              NULL,
    PRIMARY KEY CLUSTERED ([ID] ASC) WITH (FILLFACTOR = 90),
    CONSTRAINT [FK_PR_REV_PARAMS_ONLYOPTION] FOREIGN KEY ([ONLYOPTION]) REFERENCES [dbo].[PR_MODELTYPE_OPTIONS] ([ID]),
