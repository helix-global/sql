    ON [dbo].[PR_PRORDER_SERVICE]([ORDERID] ASC, [DEVICEID] ASC);


GO
CREATE NONCLUSTERED INDEX [IX_PR_PRORDER_SERVICE_FRID]
    ON [dbo].[PR_PRORDER_SERVICE]([FRID] ASC) WHERE ([FRID] IS NOT NULL);


GO
CREATE NONCLUSTERED INDEX [IX_PR_PRORDER_SERVICE_DEVICEID]
    ON [dbo].[PR_PRORDER_SERVICE]([DEVICEID] ASC);


GO
CREATE NONCLUSTERED INDEX [IX_PR_PRORDER_SERVICE]
    ON [dbo].[PR_PRORDER_SERVICE]([ORDERID] ASC);

